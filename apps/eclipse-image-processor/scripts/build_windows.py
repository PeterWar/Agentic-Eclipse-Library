"""Build the Windows application with its ICO and native version resources.

Run on Windows from the repository root: .venv\\Scripts\\python scripts/build_windows.py
"""
from pathlib import Path
import argparse
import os
import subprocess
import sys


def write_version_file(destination, version):
    """Generate the UTF-8 Python resource syntax accepted by PyInstaller."""
    numbers=tuple(int(part) for part in version.split('.'))
    if len(numbers)!=3 or any(not 0<=part<=65535 for part in numbers):
        raise ValueError('Expected a three-part Windows-compatible application version')
    numeric=(*numbers,0)
    fields={
        'CompanyName':'Francisco Bitto',
        'FileDescription':'Eclipse Image Processor',
        'FileVersion':version,
        'InternalName':'Eclipse Image Processor',
        'OriginalFilename':'Eclipse Image Processor.exe',
        'ProductName':'Eclipse Image Processor',
        'ProductVersion':version,
    }
    strings=',\n'.join(f'            StringStruct({key!r}, {value!r})' for key,value in fields.items())
    destination.write_text(f'''# UTF-8; generated by scripts/build_windows.py.
VSVersionInfo(
    ffi=FixedFileInfo(filevers={numeric!r}, prodvers={numeric!r}, mask=0x3f,
                      flags=0, OS=0x40004, fileType=0x1, subtype=0, date=(0,0)),
    kids=[StringFileInfo([StringTable('040904B0', [
{strings}
    ])]), VarFileInfo([VarStruct('Translation', [1033,1200])])]
)
''',encoding='utf-8')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    if sys.platform!='win32':
        raise SystemExit('Build the Windows application on Windows.')
    root=Path(__file__).resolve().parents[1]
    sys.path.insert(0,str(root))
    from config import APP_VERSION
    build=root/'build'/'windows'
    build.mkdir(parents=True,exist_ok=True)
    assets=root/'assets'
    icon=assets/'Eclipse_Image_Processor.ico'
    png=assets/'Eclipse_Image_Processor.png'
    for resource in (icon,png):
        if not resource.is_file():
            raise FileNotFoundError(resource)
    version_file=build/'version_info.txt'
    write_version_file(version_file,APP_VERSION)
    environment=os.environ.copy()
    environment['PYINSTALLER_CONFIG_DIR']=str(build/'cache')
    subprocess.run([
        sys.executable,'-m','PyInstaller',
        '--noconfirm','--windowed','--onedir','--name','Eclipse Image Processor',
        '--icon',str(icon),'--version-file',str(version_file),
        '--specpath',str(build),'--workpath',str(build/'work'),
        '--distpath',str(root/'dist'),
        '--add-data',f'{icon}:assets','--add-data',f'{png}:assets',
        '--add-data',f'{root / "docs" / "third-party"}:docs/third-party',
        '--add-data',f'{root / "ATTRIBUTIONS.md"}:.',
        '--add-data',f'{root / "LICENSE"}:.',
        '--collect-all','watroo','--collect-all','psd_tools',
        '--hidden-import','PIL.TiffImagePlugin',str(root/'main.py'),
    ],cwd=root,env=environment,check=True)
    print(f'Application ready: {root / "dist" / "Eclipse Image Processor" / "Eclipse Image Processor.exe"}')
    print('Distribute the entire application folder, including _internal; the executable alone is insufficient.')


if __name__=='__main__':
    main()
